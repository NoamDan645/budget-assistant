def create_model():
    load_dotenv(Path(__file__).with_name(".env"))

    llm = ChatOpenAI(
        model="gpt-4o",
        temperature=0,
    )

    return llm.bind_tools(
        TOOLS,
        parallel_tool_calls=False,
    )